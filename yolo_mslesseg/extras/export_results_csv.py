"""
Script: export_results_csv.py

Description:
    Generates a summary table from the global results obtained across different
    experiments. This script automatically searches for the JSON files generated
    by `average_folds.py` and composes a single CSV with all global metrics
    grouped by anatomical plane and enhancement algorithm.

    This script requires specifying an exact combination of experiment parameters
    (modality, number of slices, k_folds, and number of training epochs). These
    parameters define which subdirectory of results/ is to be processed. The
    `plane` and `enhancement` fields are included only to build the `Model` object,
    but do not influence result filtering, since the final CSV always incorporates
    all planes and all enhancement algorithms available for that configuration.

CLI Usage:
    python -m yolo_mslesseg.extras.export_results_csv \
        --plane axial \
        --modality FLAIR \
        --num_slices P50 \
        --epochs 50 \
        --k_folds 5

Inputs:
    - JSON files with global metrics generated by `average_folds.py` for a
      specific experiment:
            results/<enhancement>/<modality>_<num_slices>slices_<k_folds>folds_<epochs>epochs/global_<plane>_results.json

    - Classes:
        * Model → instantiated only to retrieve `model_string` and locate the correct folder.

Outputs:
    - Summary CSV with columns:
        Plane | Enhancement | DSC (mean ± std) | AUC (mean ± std) |
        Precision (mean ± std) | Recall (mean ± std)
      saved to:
        <modality>_<num_slices>slices_<k_folds>folds_<epochs>epochs_results.csv
"""

import argparse
from pathlib import Path

import pandas as pd

from yolo_mslesseg.utils.Model import Model
from yolo_mslesseg.utils.logging_config import get_logger
from yolo_mslesseg.utils.constants import EXT_JSON, PLANES, RESULTS_DIR, EXT_CSV, ENHANCEMENTS, ENHANCEMENT_BASE
from yolo_mslesseg.utils.utils import (
    read_json,
    path_exists,
    int_or_percentile,
    build_config_name,
)

logger = get_logger(__file__)

# ======================================
#           BASE FUNCTIONS
# ======================================


def list_jsons(directory: Path) -> list[Path]:
    """Returns a list of global_*.json files in the given directory.

    Args:
        directory: Directory to search for global results JSON files.

    Returns:
        List of matching file paths, or an empty list if the directory does not exist.
    """
    if not directory.exists():
        return []
    return [
        f
        for f in directory.iterdir()
        if f.is_file() and f.suffix == EXT_JSON and f.name.startswith("global_")
    ]


def parse_experiment(filepath: Path) -> tuple[str, str]:
    """Extracts the plane and enhancement labels from a results file path.

    Args:
        filepath: Path to a global results JSON file.

    Returns:
        Tuple of (plane, enhancement) derived from the path components.

    Raises:
        ValueError: If the enhancement cannot be inferred from the path.
    """
    parts = filepath.stem.split("_")
    plane = next(
        (p.capitalize() for p in parts if p.lower() in PLANES),
        "Unknown",
    )

    for parent in filepath.parents:
        name = parent.name.upper()
        if name in {e.upper() for e in ENHANCEMENTS} | {ENHANCEMENT_BASE.upper()}:
            return plane, name

    raise ValueError(f"Could not infer enhancement from path: {filepath}")


def format_json_value(value: dict | float | int) -> str:
    """Formats a metric value as a 'mean ± std' string.

    Args:
        value: Dictionary with 'mean' and 'std' keys, or a scalar value.

    Returns:
        Formatted string 'X.XXX ± Y.YYY', or an empty string if the format is unexpected.
    """
    if isinstance(value, dict) and "mean" in value and "std" in value:
        return f"{float(value['mean']):.3f} ± {float(value['std']):.3f}"
    return ""


def read_metrics_json(filepath: Path) -> dict[str, str]:
    """Reads a global results JSON file and formats its metric values.

    Args:
        filepath: Path to the JSON file to read.

    Returns:
        Dictionary mapping metric names to formatted 'mean ± std' strings.
    """
    metrics = {}

    try:
        data = read_json(filepath)
    except Exception as e:
        logger.warning(f"⚠️ Could not read JSON file {filepath}: {e}.")
        return metrics

    for metric, values in data.items():
        metrics[metric] = format_json_value(values)

    return metrics


def build_row(plane: str, enhancement: str, metrics: dict) -> dict:
    """Builds a row dictionary for the results DataFrame.

    Args:
        plane: Anatomical plane label (e.g. 'Axial').
        enhancement: Enhancement algorithm label (e.g. 'HE').
        metrics: Dictionary mapping metric names to formatted value strings.

    Returns:
        Row dictionary with keys for Enhancement, Plane, and all metric columns.
    """
    return {
        "Enhancement": enhancement,
        "Plane": plane,
        "DSC (mean ± std)": metrics.get("DSC", ""),
        "AUC (mean ± std)": metrics.get("AUC", ""),
        "Precision (mean ± std)": metrics.get("Precision", ""),
        "Recall (mean ± std)": metrics.get("Recall", ""),
    }


def sort_dataframe(df: pd.DataFrame) -> None:
    """Sorts the DataFrame in-place by plane and enhancement using a predefined order.

    Args:
        df: DataFrame to sort; must contain 'Plane' and 'Enhancement' columns.
    """
    plane_order = ["Axial", "Coronal", "Sagittal", "Consensus"]
    enhancement_order = [ENHANCEMENT_BASE, "HE", "CLAHE", "GC", "LT"]

    df["Plane"] = pd.Categorical(df["Plane"], categories=plane_order, ordered=True)
    df["Enhancement"] = pd.Categorical(df["Enhancement"], categories=enhancement_order, ordered=True)
    df.sort_values(by=["Enhancement", "Plane"], inplace=True)


# ======================================
#              PROCESSING
# ======================================


def compose_results(global_config: str) -> pd.DataFrame | None:
    """Searches for global results JSON files and composes a summary CSV.

    Args:
        global_config: Configuration string used to locate experiment result directories.

    Returns:
        DataFrame with the composed results, or None if no JSON files were found.
    """

    rows = []
    json_list = []

    logger.info(
        f"🔍 Searching experiments within global configuration {global_config}"
    )

    output_path = RESULTS_DIR / f"{global_config}_results{EXT_CSV}"

    # Iterate over all enhancement directories
    for enhancement_dir in RESULTS_DIR.iterdir():
        if not enhancement_dir.is_dir():
            continue

        experiment_dir = enhancement_dir / global_config
        if experiment_dir.exists():
            json_list.extend(list_jsons(experiment_dir))

    if not json_list:
        logger.warning(f"⚠️ No JSON files found for: {global_config}")
        return None

    logger.info(f"📂 Found {len(json_list)} JSON files")

    # Process each JSON
    for json_file in json_list:
        plane, enhancement = parse_experiment(json_file)
        metrics = read_metrics_json(json_file)
        rows.append(build_row(plane, enhancement, metrics))

    if not rows:
        logger.warning("⚠️ No valid rows were generated.")
        return None

    df = pd.DataFrame(rows)
    sort_dataframe(df)
    df["Enhancement"] = df["Enhancement"].replace("CONTROL", ENHANCEMENT_BASE).fillna(ENHANCEMENT_BASE)

    df.to_csv(output_path, index=False)
    logger.info(f"✅ Summary exported to {output_path}")

    return df


# ======================================
#               MAIN FLOW
# ======================================


def run_export_flow(model: Model, epochs: int, clean: bool) -> None:
    """Executes the results composition flow.

    Args:
        model: Model instance used to derive the experiment configuration string.
        epochs: Number of training epochs of the YOLO model.
        clean: If True, deletes the existing CSV before generating a new one.
    """
    logger.header(f"📊️ Generating results table")

    global_config = build_config_name(model, epochs)

    output_path = RESULTS_DIR / f"{global_config}_results{EXT_CSV}"

    # Clean if requested
    if clean and path_exists(output_path):
        logger.info(f"♻️ Deleting previous table.")
        output_path.unlink(missing_ok=True)

    compose_results(global_config)


# ======================================
#          CLI AND EXECUTION
# ======================================


def parse_args() -> argparse.Namespace:
    """Parses the script arguments from the command line.

    Returns:
        Namespace with the parsed CLI arguments.
    """
    parser = argparse.ArgumentParser(
        description="Compose global experiment results for the selected configuration."
    )
    parser.add_argument(
        "--plane",
        type=str,
        required=True,
        choices=["axial", "coronal", "sagittal"],
        metavar="[axial, coronal, sagittal]",
        help="Anatomical extraction plane.",
    )
    parser.add_argument(
        "--modality",
        nargs="+",
        choices=["T1", "T2", "FLAIR"],
        default=["T1", "T2", "FLAIR"],
        metavar="[T1, T2, FLAIR]",
        help="MRI modality or modalities. Defaults to all.",
    )
    parser.add_argument(
        "--num_slices",
        type=int_or_percentile,
        required=True,
        metavar="<num_slices>",
        help="Number of extracted slices (fixed value or percentile).",
    )
    parser.add_argument(
        "--enhancement",
        type=str,
        default=None,
        choices=["HE", "CLAHE", "GC", "LT"],
        metavar="<enhancement>",
        help="Image enhancement algorithm applied. Defaults to None.",
    )
    parser.add_argument(
        "--epochs",
        type=int,
        required=True,
        metavar="<epochs>",
        help="Number of training epochs.",
    )
    parser.add_argument(
        "--k_folds",
        type=int,
        default=5,
        metavar="<k_folds>",
        help="Number of folds for cross-validation. Defaults to 5.",
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        default=False,
        help="Clean previously generated results.",
    )

    return parser.parse_args()


def main() -> None:
    """CLI entry point: parses arguments, builds the Model instance, and executes the full flow."""
    args = parse_args()

    model = Model(
        plane=args.plane,
        num_slices=args.num_slices,
        modality=args.modality,
        k_folds=args.k_folds,
        enhancement=args.enhancement,
    )

    run_export_flow(
        model=model,
        epochs=args.epochs,
        clean=args.clean,
    )


if __name__ == "__main__":
    main()
