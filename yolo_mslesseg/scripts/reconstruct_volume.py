def process_patient_volume(patient_id: str, config: ConfigReconstruction, paths_dir: dict[str, Path] | None = None) -> StageResult:
    """Executes the volume reconstruction process for an individual patient.

    Checks whether the volume already exists and is valid, then reconstructs and
    validates it if needed.

    Args:
        patient_id: Patient identifier string.
        config: ConfigReconstruction instance providing model and directory settings.
        paths_dir: Dictionary of paths (pred_vol, gt_vol, pred_masks). Defaults to
            config patient paths if None.

    Returns:
        StageResult.COMPLETED if the volume was reconstructed, StageResult.SKIPPED
        if skipped (already valid).

    Raises:
        RuntimeError: If the reconstructed volume fails validation.
    """
    # If no directories are provided → patient mode → use config directories
    if paths_dir is None:
        paths_dir = {
            "pred_vol": config.patient_pred_vol,
            "gt_vol": config.patient_gt_vol,
            "pred_masks": config.patient_pred_masks,
        }

    patient_pred_vol = paths_dir["pred_vol"]
    patient_gt_vol = paths_dir["gt_vol"]
    patient_pred_masks = paths_dir["pred_masks"]

    # Check if a reconstructed volume already exists
    if not needs_reconstruction(patient_pred_vol):

        # If it exists, validate it against the ground truth
        if not is_valid_reconstruction(
            pred_vol_path=patient_pred_vol,
            gt_vol_path=patient_gt_vol,
        ):
            # If invalid, mark for reconstruction
            logger.warning(
                f"⚠️ Invalid reconstruction for {patient_id}, must be redone."
            )
            reconstruction_needed = True
        else:
            return StageResult.SKIPPED
    else:
        reconstruction_needed = True

    # Reconstruct and validate the result
    if reconstruction_needed:
        reconstruct_volume(
            pred_masks_dir=patient_pred_masks,
            reference_volume=patient_gt_vol,
            output_path=patient_pred_vol,
            plane=config.model.plane,
        )
        if not is_valid_reconstruction(
            pred_vol_path=patient_pred_vol, gt_vol_path=patient_gt_vol
        ):
            raise RuntimeError(f"Validation failed for {patient_id}.")
        return StageResult.COMPLETED


def build_paths(patient_id: str, config: ConfigReconstruction) -> dict[str, Path]:
    """Builds the predicted volume, GT volume, and pred_masks paths for a patient.

    Args:
        patient_id: Patient identifier string.
        config: ConfigReconstruction instance providing directory and plane settings.

    Returns:
        Dictionary with keys 'pred_vol', 'gt_vol', and 'pred_masks' mapping to Path objects.
    """
    root_pred_vols = config.pred_vols_fold_dir / patient_id
    root_gt = config.gt_dir / patient_id
    root_dataset = config.dataset_fold_dir / patient_id / config.plane
    pred_masks_dir = root_dataset / "pred_masks"

    return {
        "pred_vol": root_pred_vols / f"{patient_id}_{config.plane}{EXT_NIFTI}",
        "gt_vol": root_gt / f"{patient_id}{MASK_SUFFIX}{EXT_NIFTI}",
        "pred_masks": pred_masks_dir,
    }


def reconstruct_volumes_for_patients(input_dir: Path, config: ConfigReconstruction) -> StageResult:
    """Executes the volume reconstruction process for all patients in a directory.

    Args:
        input_dir: Directory containing patient subdirectories to process.
        config: ConfigReconstruction instance providing model and directory settings.

    Returns:
        StageResult.COMPLETED if all patients were processed, StageResult.SKIPPED
        if all were skipped, or StageResult.PARTIAL if there was a mix.
    """
    patients = list_patients(input_dir)

    results = []
    for patient_id in patients:
        patient_paths = build_paths(patient_id, config)
        try:
            reconstructed = process_patient_volume(
                patient_id=patient_id, config=config, paths_dir=patient_paths
            )
            results.append(reconstructed)
        except Exception as e:
            logger.warning(
                f"⚠️ Error reconstructing volumes for {patient_id}, skipping: {e}.",
            )
            continue

    return evaluate_results(results)


# ======================================
#               MAIN FLOW
# ======================================


def run_volume_flow(config: ConfigReconstruction, clean: bool, verbose: bool = False) -> None:
    """Executes the main volume reconstruction flow.

    Args:
        config: ConfigReconstruction instance defining the reconstruction configuration.
        clean: If True, deletes existing reconstructed volumes before regenerating.
        verbose: If True, logs a header message at the start of execution.
    """

    if verbose:
        if config.is_individual_patient:
            str_header = f"patient {config.patient}"
        elif config.single_fold:
            str_header = f"group {config.group}"
        else:
            str_header = f"fold {config.fold_test}"

        logger.header(f"\n🧱 Reconstructing volume(s) for {str_header}.")

    # Clean if requested
    if clean:
        if verbose:
            logger.info(f"♻️ Cleaning previous volumes.")
        config.clean()

    # Verify paths
    config.verify_paths()

    # Patient execution
    if config.is_individual_patient:
        patient_id = config.patient.id
        reconstructed = process_patient_volume(
            patient_id=patient_id, config=config
        )
        if reconstructed is StageResult.SKIPPED:
            logger.skip(f"⏩ Reconstructed volume already exists.")
        elif reconstructed is StageResult.COMPLETED:
            logger.info(f"✅ Volume reconstructed and validated successfully.")
        else:
            logger.warning(f"⚠️ Unknown status when reconstructing volume.")

    # Fold execution
    else:
        reconstructed = reconstruct_volumes_for_patients(
            input_dir=config.dataset_fold_dir, config=config
        )
        if config.k_folds == 1:
            if reconstructed is StageResult.SKIPPED:
                logger.skip(f"⏩ Volumes for {config.group} already exist.")
            elif reconstructed is StageResult.COMPLETED:
                logger.info(f"🆗 Volumes for {config.group} reconstructed successfully.")
            elif reconstructed is StageResult.PARTIAL:
                logger.info(
                    f"🔁 Volumes for {config.group} partially updated."
                )
            else:
                logger.warning("⚠️ Unknown status when reconstructing volumes.")

        else:
            log_fold_status(
                logger=logger,
                result=reconstructed,
                fold=config.fold_test,
            )


