"""
Script: reconstruct_volume.py

Description:
    Reconstructs 3D NIfTI volumes from the 2D prediction masks generated by the
    YOLO model, either for an individual patient or for all patients in a fold.
    Reconstructed volumes are automatically validated against the ground truth
    masks and stored in the pred_vols/ directory.

Execution modes:
    1. CLI (standalone):
       - Arguments are read and parsed from the command line.
       - Model and (optionally) Patient instances are created.

    2. Internal (from `run_pipeline.py`):
       - Pre-built Model and (optionally) Patient instances are received,
         along with the remaining parameters.
       - The argument parser is not used.

CLI Usage:
    python -m yolo_mslesseg.scripts.reconstruct_volume \
        --plane sagittal \
        --num_slices P75 \
        --epochs 25 \
        --fold_test 1

Inputs:
    - Predicted 2D masks (.png): generated previously with `generate_predictions.py`,
        in the pred_masks/ subdirectory within each patient.

    - Ground truth (.nii.gz): original volumes located in GT/<patient_id>/
        used as reference for reconstruction and validation.

    - Classes:
        * ConfigReconstruction → manages paths and global variables for reconstruction.
        * Model                → defines the plane, modalities, enhancement, and num_slices.

Outputs:
    - Reconstructed volumes (.nii.gz) in
    pred_vols/<enhancement>/<modality>_<num_slices>slices_<k_folds>folds_<epochs>epochs/<fold_test>/PX/
"""

import argparse
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image

from yolo_mslesseg.configs.ConfigReconstruction import ConfigReconstruction
from yolo_mslesseg.utils.Model import Model
from yolo_mslesseg.utils.Patient import Patient
from yolo_mslesseg.utils.logging_config import get_logger
from yolo_mslesseg.utils.constants import EXT_PNG, EXT_NIFTI, MASK_SUFFIX, ENHANCEMENTS, StageResult
from yolo_mslesseg.utils.utils import (
    save_volume,
    int_or_percentile,
    path_exists,
    list_patients,
    load_nifti_reference,
    evaluate_results,
    is_valid_reconstruction,
    log_fold_status,
)

# Configure logger
logger = get_logger(__file__)


